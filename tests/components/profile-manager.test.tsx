import {render,screen,fireEvent,within} from "@testing-library/react";
import {beforeEach,expect,it,vi} from "vitest";
import {Demo} from "@/github-pages/Demo";
import {loadProfiles,profilesKey,createProfile,profileStores,selectProfile} from "@/github-pages/profiles";
import {feelingWords} from "@/features/content/feelings-lesson";
import {verbCards} from "@/features/cards/data/verb-cards";
// These tests exercise the existing synchronous profile stores; IndexedDB is verified separately.
vi.mock("@/github-pages/LocalLearningBoundary",()=>({LocalLearningBoundary:({children}:{children:React.ReactNode})=>children}));

beforeEach(()=>{window.localStorage.clear();window.history.replaceState(null,"","/tempo-react/");vi.spyOn(window,"scrollTo").mockImplementation(()=>{});});
it.each([true,false])("opens and restores a profile (child=%s) without the casing collision",child=>{
  const view=render(<Demo/>);
  expect(screen.queryByRole("group",{name:"Выбери аватар"})).not.toBeInTheDocument();
  fireEvent.change(screen.getByRole("textbox",{name:"Имя"}),{target:{value:"QA"}});
  fireEvent.click(screen.getByRole("radio",{name:child?"Ребёнок":"Взрослый"}));
  fireEvent.click(screen.getByRole("button",{name:"Создать профиль и начать"}));
  const registry=loadProfiles();
  expect(registry.profiles).toHaveLength(1);
  expect(registry.profiles[0].child).toBe(child);
  expect(screen.getByRole("heading",{name:"Общий план"})).toBeVisible();
  fireEvent.click(screen.getByRole("link",{name:"Короткий урок: SER →"}));
  if(child)expect(screen.getByRole("img",{name:"Мальчик"})).toHaveTextContent("👦");
  expect(screen.getByRole("img",{name:"Люди, роли и происхождение"})).toHaveAttribute("src",child?"/ser-guide-kingdoms.webp":"/ser-guide-adult.webp");
  const saved=window.localStorage.getItem(profilesKey);
  expect(screen.queryByRole("button",{name:"Создать профиль и начать"})).toBeNull();
  view.unmount();render(<Demo/>);
  expect(window.localStorage.getItem(profilesKey)).toBe(saved);
  expect(screen.queryByRole("button",{name:"Создать профиль и начать"})).toBeNull();
});
it("isolates rewards and presentation, resumes the theme and preserves rewards through plan writes",()=>{
  const child=createProfile("Ребёнок QA",true,false),adult=createProfile("Взрослый QA",false,false);
  const stores=profileStores(child.id),learning=stores.learning.load();
  stores.learning.save({...learning,lastTopicId:"topic:people",feelings:{...learning.feelings,viewed:feelingWords.slice(1).map(word=>word.id)}});
  selectProfile(child.id);
  const view=render(<Demo/>);
  fireEvent.click(screen.getByRole("link",{name:"Все темы"}));
  const lesson=screen.getByRole("region",{name:"Как я себя чувствую: слова и ESTAR"});
  expect(lesson).toHaveAttribute("data-presentation","child");
  expect(screen.queryByRole("button",{name:"Для взрослых"})).toBeNull();
  fireEvent.click(screen.getByRole("button",{name:"Перевернуть карточку"}));
  expect(stores.learning.load().feelings.viewed).toHaveLength(6);
  stores.plan.save({...stores.plan.load(),completed:{"practice:grammar:ser":{revision:1,needsReview:false}}});
  expect(stores.learning.load().feelings.viewed).toHaveLength(6);
  view.unmount();render(<Demo/>);
  expect(screen.getByLabelText("Знакомство: получено")).toBeVisible();
  fireEvent.click(screen.getByRole("link",{name:"Карточки"}));
  expect(screen.getByRole("region",{name:"Колоды карточек"})).toBeVisible();
  fireEvent.click(screen.getByRole("link",{name:"Все темы"}));
  expect(screen.getByRole("heading",{name:"Aulas — Уроки"})).toBeVisible();
  expect(stores.plan.load().completed["practice:grammar:ser"]).toEqual({revision:1,needsReview:false});
  expect(stores.learning.load().feelings.viewed).toHaveLength(6);
  fireEvent.click(screen.getByRole("button",{name:"Сменить профиль или настройки"}));
  expect(within(screen.getByRole("article",{name:"Профиль Ребёнок QA"})).getByText(/Награды: 2/)).toBeVisible();
  expect(within(screen.getByRole("article",{name:"Профиль Взрослый QA"})).getByText(/Награды: 0/)).toBeVisible();
  fireEvent.click(screen.getByRole("button",{name:"Продолжить — Взрослый QA"}));
  fireEvent.click(screen.getByRole("link",{name:"Все темы"}));
  fireEvent.click(screen.getByRole("button",{name:/^Como me sinto\?/}));
  expect(screen.getByRole("region",{name:"Как я себя чувствую: слова и ESTAR"})).toHaveAttribute("data-presentation","adult");
  expect(screen.getByLabelText("Знакомство: впереди")).toBeVisible();
  expect(profileStores(adult.id).learning.load().feelings.viewed).toHaveLength(0);
},20000);
it("does not award before storage succeeds and retries without losing the previous profile data",()=>{
  const profile=createProfile("Сохранение QA",true,false),stores=profileStores(profile.id),learning=stores.learning.load();
  stores.learning.save({...learning,lastTopicId:"topic:people",feelings:{...learning.feelings,viewed:feelingWords.slice(1).map(word=>word.id)}});
  render(<Demo/>);
  fireEvent.click(screen.getByRole("link",{name:"Все темы"}));
  const save=vi.spyOn(Storage.prototype,"setItem").mockImplementation(()=>{throw new Error("quota");});
  fireEvent.click(screen.getByRole("button",{name:"Перевернуть карточку"}));
  expect(screen.getByLabelText("Знакомство: впереди")).toBeVisible();
  expect(stores.learning.load().feelings.viewed).toHaveLength(5);
  expect(screen.getByRole("button",{name:"Сменить профиль или настройки"})).toBeDisabled();
  save.mockRestore();
  fireEvent.click(screen.getByRole("button",{name:"Сохранить результаты ещё раз"}));
  expect(stores.learning.load().feelings.viewed).toHaveLength(6);
  expect(screen.getByLabelText("Знакомство: получено")).toBeVisible();
  expect(screen.getByRole("button",{name:"Сменить профиль или настройки"})).toBeEnabled();
});
it("reads old profile data without rewriting it and keeps cards when learning is saved",()=>{
  const profile=createProfile("Старый профиль",false,false),stores=profileStores(profile.id);
  const key=`tempo-react:github-pages:profile:${profile.id}:v1`,original=localStorage.getItem(key);
  expect(original).not.toContain('"learning"');
  expect(stores.learning.load().feelings.viewed).toEqual([]);
  expect(localStorage.getItem(key)).toBe(original);
  const card={cardId:verbCards[0].id,due:1,interval:1,ease:2.5,repetitions:1,lapses:0,lastGrade:2};
  stores.cards.save(card);
  stores.learning.save({...stores.learning.load(),lastTopicId:"topic:people"});
  expect(stores.cards.load()).toEqual([card]);
  stores.cards.save({...card,repetitions:2});
  expect(stores.learning.load().lastTopicId).toBe("topic:people");
});
it("preserves malformed profile data and keeps the other learner available",()=>{
  const healthy=createProfile("Исправный",false,false),broken=createProfile("Повреждённый",true,false);
  const key=`tempo-react:github-pages:profile:${broken.id}:v1`,bad='{"version":1,"learning":"broken"}';
  localStorage.setItem(key,bad);
  render(<Demo/>);
  expect(screen.getByRole("button",{name:`Продолжить — ${healthy.name}`})).toBeVisible();
  expect(screen.queryByRole("button",{name:`Продолжить — ${broken.name}`})).toBeNull();
  expect(localStorage.getItem(key)).toBe(bad);
});
